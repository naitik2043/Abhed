-- Abhed production database setup.
-- Run once in the Supabase SQL Editor for the project used by the app.

create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create schema if not exists abhed_private;
revoke all on schema abhed_private from public, anon, authenticated;

create table if not exists abhed_private.accounts (
  id uuid primary key,
  email text not null unique,
  password_hash text not null,
  name text not null,
  company text,
  role text,
  created_at timestamptz not null default now(),
  last_login_at timestamptz,
  failed_attempts integer not null default 0,
  locked_until timestamptz,
  title text,
  phone text,
  location text,
  website text,
  bio text,
  avatar text,
  avatar_v bigint
);

create table if not exists abhed_private.sessions (
  token_hash text primary key,
  account_id uuid not null references abhed_private.accounts(id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index if not exists abhed_sessions_account_idx on abhed_private.sessions(account_id);

create table if not exists abhed_private.contact_messages (
  id bigint generated by default as identity primary key,
  account_id uuid references abhed_private.accounts(id) on delete set null,
  name text not null,
  email text not null,
  topic text,
  message text not null,
  created_at timestamptz not null default now()
);

alter table abhed_private.accounts enable row level security;
alter table abhed_private.sessions enable row level security;
alter table abhed_private.contact_messages enable row level security;
revoke all privileges on all tables in schema abhed_private from public, anon, authenticated, service_role;

-- This table stores the app's shared governance state. Only the Vercel server's
-- secret API key can read or write it; the publishable key gets no table access.
create table if not exists public.kavach_state (
  id text primary key,
  version bigint not null,
  world jsonb not null,
  updated_at timestamptz not null default now()
);
alter table public.kavach_state enable row level security;
revoke all privileges on table public.kavach_state from public, anon, authenticated;
grant select, insert, update, delete on table public.kavach_state to service_role;
drop policy if exists kavach_state_server_access on public.kavach_state;
create policy kavach_state_server_access on public.kavach_state
  for all to service_role using (true) with check (true);

create or replace function abhed_private.account_json(p_account_id uuid)
returns jsonb
language sql
stable
set search_path = pg_catalog, extensions, pg_temp
as $function$
  select jsonb_build_object(
    'id', a.id::text,
    'email', a.email,
    'name', a.name,
    'company', a.company,
    'role', a.role,
    'created_at', a.created_at,
    'last_login_at', a.last_login_at,
    'title', a.title,
    'phone', a.phone,
    'location', a.location,
    'website', a.website,
    'bio', a.bio,
    'avatar_v', a.avatar_v
  )
  from abhed_private.accounts as a
  where a.id = p_account_id;
$function$;
revoke all on function abhed_private.account_json(uuid) from public, anon, authenticated;

create or replace function public.abhed_signup(
  p_email text,
  p_password text,
  p_name text,
  p_company text,
  p_role text
)
returns table (
  id uuid, email text, name text, company text, role text, created_at timestamptz,
  last_login_at timestamptz, title text, phone text, location text, website text,
  bio text, avatar_v bigint, token text
)
language plpgsql
security definer
set search_path = pg_catalog, extensions, pg_temp
as $function$
declare
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_password text := coalesce(p_password, '');
  v_name text := btrim(coalesce(p_name, ''));
  v_company text := nullif(btrim(coalesce(p_company, '')), '');
  v_role text := nullif(btrim(coalesce(p_role, '')), '');
  v_password_digest text;
  v_token text;
  v_account abhed_private.accounts%rowtype;
begin
  if v_email !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' or char_length(v_email) > 160 then
    raise exception using message = 'bad_email';
  end if;
  if char_length(v_password) < 8 or char_length(v_password) > 200 then
    raise exception using message = 'weak_password';
  end if;
  if char_length(v_name) < 2 or char_length(v_name) > 80 then
    raise exception using message = 'bad_name';
  end if;
  if char_length(coalesce(v_company, '')) > 80 or char_length(coalesce(v_role, '')) > 40 then
    raise exception using message = 'bad_name';
  end if;

  -- Pre-hash to 32 bytes before bcrypt so passwords longer than bcrypt's
  -- 72-byte input boundary are not silently treated as the same password.
  v_password_digest := encode(extensions.digest(convert_to(v_password, 'UTF8'), 'sha256'), 'base64');
  v_token := encode(extensions.gen_random_bytes(32), 'hex');

  insert into abhed_private.accounts (
    id, email, password_hash, name, company, role, created_at, last_login_at
  ) values (
    gen_random_uuid(), v_email,
    extensions.crypt(v_password_digest, extensions.gen_salt('bf', 12)),
    v_name, v_company, v_role, now(), now()
  ) returning * into v_account;

  insert into abhed_private.sessions (token_hash, account_id, expires_at)
  values (
    encode(extensions.digest(convert_to(v_token, 'UTF8'), 'sha256'), 'hex'),
    v_account.id,
    now() + interval '7 days'
  );

  return query select
    v_account.id, v_account.email, v_account.name, v_account.company, v_account.role,
    v_account.created_at, v_account.last_login_at, v_account.title, v_account.phone,
    v_account.location, v_account.website, v_account.bio, v_account.avatar_v, v_token;
exception
  when unique_violation then
    raise exception using message = 'email_taken';
end;
$function$;

create or replace function public.abhed_signin(p_email text, p_password text)
returns table (
  id uuid, email text, name text, company text, role text, created_at timestamptz,
  last_login_at timestamptz, title text, phone text, location text, website text,
  bio text, avatar_v bigint, status text, token text
)
language plpgsql
security definer
set search_path = pg_catalog, extensions, pg_temp
as $function$
declare
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_password_digest text;
  v_token text;
  v_account abhed_private.accounts%rowtype;
begin
  select a.* into v_account
  from abhed_private.accounts as a
  where a.email = v_email
  for update;

  if not found then
    return query select null::uuid, null::text, null::text, null::text, null::text,
      null::timestamptz, null::timestamptz, null::text, null::text, null::text,
      null::text, null::text, null::bigint, 'invalid'::text, null::text;
    return;
  end if;

  if v_account.locked_until is not null and v_account.locked_until > now() then
    return query select null::uuid, null::text, null::text, null::text, null::text,
      null::timestamptz, null::timestamptz, null::text, null::text, null::text,
      null::text, null::text, null::bigint, 'locked'::text, null::text;
    return;
  end if;

  v_password_digest := encode(extensions.digest(convert_to(coalesce(p_password, ''), 'UTF8'), 'sha256'), 'base64');
  if extensions.crypt(v_password_digest, v_account.password_hash) <> v_account.password_hash then
    update abhed_private.accounts as a
    set failed_attempts = a.failed_attempts + 1,
        locked_until = case when a.failed_attempts + 1 >= 8 then now() + interval '15 minutes' else a.locked_until end
    where a.id = v_account.id;
    return query select null::uuid, null::text, null::text, null::text, null::text,
      null::timestamptz, null::timestamptz, null::text, null::text, null::text,
      null::text, null::text, null::bigint, 'invalid'::text, null::text;
    return;
  end if;

  v_token := encode(extensions.gen_random_bytes(32), 'hex');
  update abhed_private.accounts as a
  set failed_attempts = 0, locked_until = null, last_login_at = now()
  where a.id = v_account.id
  returning * into v_account;

  insert into abhed_private.sessions (token_hash, account_id, expires_at)
  values (
    encode(extensions.digest(convert_to(v_token, 'UTF8'), 'sha256'), 'hex'),
    v_account.id,
    now() + interval '7 days'
  );

  return query select
    v_account.id, v_account.email, v_account.name, v_account.company, v_account.role,
    v_account.created_at, v_account.last_login_at, v_account.title, v_account.phone,
    v_account.location, v_account.website, v_account.bio, v_account.avatar_v, 'ok'::text, v_token;
end;
$function$;

create or replace function public.abhed_profile(p_token text)
returns jsonb
language sql
stable
security definer
set search_path = pg_catalog, extensions, pg_temp
as $function$
  select abhed_private.account_json(s.account_id)
  from abhed_private.sessions as s
  where s.token_hash = encode(extensions.digest(convert_to(coalesce(p_token, ''), 'UTF8'), 'sha256'), 'hex')
    and s.expires_at > now();
$function$;

create or replace function public.abhed_profile_save(p_token text, p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, extensions, pg_temp
as $function$
declare
  v_patch jsonb := coalesce(p, '{}'::jsonb);
  v_account_id uuid;
  v_key text;
  v_limit integer;
begin
  if jsonb_typeof(v_patch) <> 'object' then
    raise exception using message = 'bad_profile';
  end if;
  if exists (
    select 1 from jsonb_object_keys(v_patch) as k(key)
    where k.key not in ('name', 'company', 'role', 'title', 'phone', 'location', 'website', 'bio', 'avatar')
  ) then
    raise exception using message = 'bad_profile';
  end if;

  for v_key, v_limit in
    select limits.key, limits.max_length from (values
      ('name', 80), ('company', 80), ('role', 40), ('title', 80), ('phone', 30),
      ('location', 80), ('website', 200), ('bio', 400), ('avatar', 400000)
    ) as limits(key, max_length)
  loop
    if v_patch ? v_key then
      if jsonb_typeof(v_patch -> v_key) <> 'string' or char_length(v_patch ->> v_key) > v_limit then
        raise exception using message = case when v_key = 'avatar' then 'bad_photo' else 'bad_profile' end;
      end if;
    end if;
  end loop;

  if v_patch ? 'name' and char_length(btrim(v_patch ->> 'name')) < 2 then
    raise exception using message = 'bad_name';
  end if;
  if v_patch ? 'avatar' and v_patch ->> 'avatar' <> ''
    and (v_patch ->> 'avatar') !~ '^data:image/(jpeg|png|webp);base64,[A-Za-z0-9+/=]+$' then
    raise exception using message = 'bad_photo';
  end if;
  if v_patch ? 'website' and nullif(btrim(v_patch ->> 'website'), '') is not null
    and (btrim(v_patch ->> 'website') !~* '^https?://[^[:space:]]+\.[^[:space:]]+$') then
    raise exception using message = 'bad_website';
  end if;

  select s.account_id into v_account_id
  from abhed_private.sessions as s
  where s.token_hash = encode(extensions.digest(convert_to(coalesce(p_token, ''), 'UTF8'), 'sha256'), 'hex')
    and s.expires_at > now();
  if not found then return null; end if;

  update abhed_private.accounts as a
  set name = case when v_patch ? 'name' then btrim(v_patch ->> 'name') else a.name end,
      company = case when v_patch ? 'company' then nullif(btrim(v_patch ->> 'company'), '') else a.company end,
      role = case when v_patch ? 'role' then nullif(btrim(v_patch ->> 'role'), '') else a.role end,
      title = case when v_patch ? 'title' then nullif(btrim(v_patch ->> 'title'), '') else a.title end,
      phone = case when v_patch ? 'phone' then nullif(btrim(v_patch ->> 'phone'), '') else a.phone end,
      location = case when v_patch ? 'location' then nullif(btrim(v_patch ->> 'location'), '') else a.location end,
      website = case when v_patch ? 'website' then nullif(btrim(v_patch ->> 'website'), '') else a.website end,
      bio = case when v_patch ? 'bio' then nullif(btrim(v_patch ->> 'bio'), '') else a.bio end,
      avatar = case when v_patch ? 'avatar' then nullif(v_patch ->> 'avatar', '') else a.avatar end,
      avatar_v = case when v_patch ? 'avatar' then
        case when v_patch ->> 'avatar' = '' then null else (extract(epoch from clock_timestamp()) * 1000)::bigint end
        else a.avatar_v end
  where a.id = v_account_id;

  return abhed_private.account_json(v_account_id);
end;
$function$;

create or replace function public.abhed_avatar(p_token text)
returns text
language sql
stable
security definer
set search_path = pg_catalog, extensions, pg_temp
as $function$
  select a.avatar
  from abhed_private.sessions as s
  join abhed_private.accounts as a on a.id = s.account_id
  where s.token_hash = encode(extensions.digest(convert_to(coalesce(p_token, ''), 'UTF8'), 'sha256'), 'hex')
    and s.expires_at > now();
$function$;

create or replace function public.abhed_logout(p_token text)
returns void
language sql
security definer
set search_path = pg_catalog, extensions, pg_temp
as $function$
  delete from abhed_private.sessions as s
  where s.token_hash = encode(extensions.digest(convert_to(coalesce(p_token, ''), 'UTF8'), 'sha256'), 'hex');
$function$;

create or replace function public.abhed_contact(
  p_name text, p_email text, p_topic text, p_message text, p_token text
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, extensions, pg_temp
as $function$
declare
  v_name text := btrim(coalesce(p_name, ''));
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_topic text := nullif(btrim(coalesce(p_topic, '')), '');
  v_message text := btrim(coalesce(p_message, ''));
  v_account_id uuid;
  v_id bigint;
begin
  if char_length(v_name) < 2 or char_length(v_name) > 80 then
    raise exception using message = 'bad_name';
  end if;
  if v_email !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' or char_length(v_email) > 160 then
    raise exception using message = 'bad_email';
  end if;
  if char_length(v_topic) > 40 or char_length(v_message) > 4000 then
    raise exception using message = 'short_message';
  end if;
  if char_length(v_message) < 10 then
    raise exception using message = 'short_message';
  end if;

  if nullif(p_token, '') is not null then
    select s.account_id into v_account_id
    from abhed_private.sessions as s
    where s.token_hash = encode(extensions.digest(convert_to(p_token, 'UTF8'), 'sha256'), 'hex')
      and s.expires_at > now();
  end if;

  insert into abhed_private.contact_messages(account_id, name, email, topic, message)
  values (v_account_id, v_name, v_email, v_topic, v_message)
  returning id into v_id;
  return v_id;
end;
$function$;

