import { effectiveOutcomes, nameOf, verifyLedger } from '@/lib/engine';
import { getWorld } from '@/lib/store';
import { PrintButton } from './print';
import './report.css';

export const dynamic = 'force-dynamic';

const inr = (n: number) => `₹${Math.round(n).toLocaleString('en-IN')}`;
const ts = (t: number) => new Date(t).toLocaleString('en-IN', { dateStyle: 'medium', timeStyle: 'medium', hour12: false });

export default async function Report({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const w = await getWorld();
  const inc = w.incidents.find((i) => i.id === id);
  if (!inc) return <main className="rp"><h1>Incident {id} not found</h1></main>;
  const v = verifyLedger(w);
  const outcomes = effectiveOutcomes(w);
  const src = w.ledger.find((r) => r.seq === inc.sourceSeq);
  const cited = w.ledger.filter(
    (r) =>
      r.seq === inc.sourceSeq ||
      r.meta?.forSeq === inc.sourceSeq ||
      (r.action === 'confirm_root_cause' && r.params.incident === inc.id) ||
      (r.action === 'replay') ||
      (inc.ruleApprovalId && (r.meta?.approvalId === inc.ruleApprovalId || r.params.approval === inc.ruleApprovalId)),
  );
  const rule = w.rules.find((r) => r.id === 'BENEFICIARY-CHANGE' && r.active);
  const owner = w.humans.find((h) => h.id === inc.ownerId);

  return (
    <main className="rp">
      <header className="rp-head">
        <div>
          <div className="rp-k">NovaBank (fictional) · AI incident report · generated by Abhed</div>
          <h1>
            {inc.id}: {inc.title}
          </h1>
          <div className="rp-meta">
            Opened {ts(inc.openedAt)} · type {inc.type.replace('_', ' ')} · severity {inc.severity} · status {inc.status.replace(/_/g, ' ')} · owner {owner?.name} ({owner?.title})
          </div>
        </div>
        <PrintButton />
      </header>

      <section>
        <h2>1. Summary</h2>
        <p>
          {src ? `${src.actorName} (on behalf of ${src.onBehalfOf}) executed “${String(src.meta?.desc ?? src.action)}” at ${ts(src.ts)} under ${src.ruleRef}, with ${src.approvers.length ? `approval by ${src.approvers.join(' + ')}` : 'no human approver'}. ` : ''}
          The outcome is now <b>{src ? outcomes.get(src.seq) ?? src.outcome : '—'}</b>. Suggested root cause: <b>{inc.suggestedCause}</b>
          {inc.confirmedCause ? `; confirmed by ${inc.confirmedBy} as “${inc.confirmedCause}”` : '; awaiting human confirmation'}.
        </p>
        <p className="rp-muted">{inc.causeWhy}</p>
      </section>

      <section>
        <h2>2. Accountability chain</h2>
        <table>
          <thead>
            <tr>
              <th>Step</th>
              <th>Who / what</th>
              <th>Role</th>
              <th>Detail</th>
            </tr>
          </thead>
          <tbody>
            {inc.chain.map((n, i) => (
              <tr key={i}>
                <td>{i + 1}</td>
                <td>
                  <b>{n.title}</b>
                </td>
                <td>{n.role}</td>
                <td>{n.sub}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </section>

      <section>
        <h2>3. Timeline</h2>
        <ul>
          {inc.timeline.map((t, i) => (
            <li key={i}>
              <span className="rp-mono">{ts(t.ts)}</span>: {t.text}
            </li>
          ))}
        </ul>
      </section>

      {inc.corrective && (
        <section>
          <h2>4. Corrective action and proof</h2>
          <p>
            New rule <b>{inc.corrective.ruleId}</b>: “{inc.corrective.says}” Owner {nameOf(w, inc.corrective.owner)}, due {inc.corrective.due}.
          </p>
          {inc.replay && (
            <p>
              Replay over the last {inc.replay.days} days ({inc.replay.scanned} executed refunds, same rule engine as production): would have held {inc.replay.held}; {inc.replay.caught} later disputed
              (caught); {inc.replay.confirmedFine} confirmed fine (cost: {inc.replay.confirmedFine} extra approvals over 30 days); legitimate refunds blocked: {inc.replay.blockedLegit}. Records:{' '}
              {inc.replay.heldSeqs.map((s) => `#${s}`).join(', ')}.
            </p>
          )}
          <p>
            Rule status: {rule ? `ACTIVE as v${rule.version}, authored by ${nameOf(w, rule.author)}, approved by ${rule.approvedBy} (second person; author cannot self-approve).` : 'not yet active: waiting for a second person.'}
          </p>
        </section>
      )}

      <section>
        <h2>5. Ledger records cited</h2>
        <table>
          <thead>
            <tr>
              <th>#</th>
              <th>Time</th>
              <th>Actor</th>
              <th>Decision</th>
              <th>Rule</th>
              <th>Approvers</th>
              <th>Reason</th>
              <th>Hash</th>
            </tr>
          </thead>
          <tbody>
            {cited.map((r) => (
              <tr key={r.seq}>
                <td>{r.seq}</td>
                <td className="rp-mono">{ts(r.ts)}</td>
                <td>{r.actorName}</td>
                <td>{r.decision}</td>
                <td className="rp-mono">{r.ruleRef ?? '—'}</td>
                <td>{r.approvers.join(' + ') || '—'}</td>
                <td>{r.reason}</td>
                <td className="rp-mono">{r.hash.slice(0, 16)}…</td>
              </tr>
            ))}
          </tbody>
        </table>
        <p className={v.valid ? 'rp-ok' : 'rp-bad'}>
          Ledger verification at {ts(Date.now())}: {v.valid ? `chain intact across ${v.checked} records.` : `CHAIN BROKEN at record #${v.firstBadSeq}: history was edited outside Abhed.`} Personal data (account, phone, PAN,
          email) is masked before writing.
        </p>
      </section>

      <section>
        <h2>6. Framework mapping (maps to; not a compliance claim)</h2>
        <table>
          <tbody>
            <tr>
              <td>RBI FREE-AI (Aug 2025)</td>
              <td>AI inventory → agent registry; accountability → owner + delegation chain; incident reporting + audit → this report.</td>
            </tr>
            <tr>
              <td>EU AI Act Art. 12 / 14</td>
              <td>Automatic event logging (hash-chained ledger); human oversight with a stop button (pause + key revocation) and automation-bias controls (evidence-first card, rubber-stamp detection).</td>
            </tr>
            <tr>
              <td>OWASP Agentic Top 10 (2026)</td>
              <td>ASI01 goal hijack, ASI02 tool misuse, ASI03 privilege abuse, ASI09 human-agent trust exploitation, ASI10 rogue agents.</td>
            </tr>
            <tr>
              <td>DPDP Act 2023</td>
              <td>Masking before storage, purpose-scoped data access per agent.</td>
            </tr>
          </tbody>
        </table>
      </section>

      <section className="rp-sign">
        <div>
          Incident owner
          <br />
          <b>{owner?.name}</b>
        </div>
        <div>
          Root cause confirmed by
          <br />
          <b>{inc.confirmedBy ?? '—'}</b>
        </div>
        <div>
          Rule approved by
          <br />
          <b>{rule?.approvedBy ?? '—'}</b>
        </div>
      </section>
    </main>
  );
}
